const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict');
const cfg = require('../tools/workflow.config.json');
const ts = require(cfg.typescript.replace(/tsc\.js$/, 'typescript.js'));
const exportsPC = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('pc/game/PCInputGate.ts','utf8'),{compilerOptions:{module:1,target:4}}).outputText,{exports:exportsPC});
const gate = new exportsPC.PCInputGate();
const first = gate.begin();
assert.ok(first > 0);
assert.equal(gate.begin(), null, 'mouse and keyboard cannot accept two concurrent commands');
assert.equal(gate.finish(first + 1), false, 'stale completion cannot unlock current action');
assert.equal(gate.locked, true);
assert.equal(gate.finish(first), true);
const second = gate.begin();
assert.notEqual(second, first);
assert.equal(gate.finish(first), false);
assert.equal(gate.finish(second), true);
assert.equal(gate.keyDown(49), true);
assert.equal(gate.keyDown(49), false, 'held keys must not repeat');
gate.keyUp(49);
assert.equal(gate.keyDown(49), true);
gate.clearKeys();
assert.equal(gate.keyDown(49), true);
console.log('PC input: shared barrier, stale callbacks and held-key prevention passed');
