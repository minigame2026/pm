"""Compile the checked-in translation tables. OpenCC is a build-only dependency."""
import json
from pathlib import Path
from opencc import OpenCC

root = Path(__file__).resolve().parents[1]
traditional = OpenCC("s2twp")
data = {}
for source in sorted((root / "tools/locales").glob("*.tsv")):
    for number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
        if not line:
            continue
        fields = [value.replace(r"\n", "\n") for value in line.split("\t")]
        if len(fields) != 5:
            raise ValueError(f"{source.name}:{number}: expected 5 columns, got {len(fields)}")
        zh, en, ja, ko, th = fields
        if zh in data:
            raise ValueError(f"Duplicate translation: {zh}")
        data[zh] = [en, ja, ko, traditional.convert(zh), th]
out = "// Generated by tools/build-locales.py; edit tools/locales/*.tsv.\n"
out += "export const TRANSLATIONS:Record<string,string[]>=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "assets/scripts/PMTranslations.ts").write_text(out, encoding="utf-8")
print(f"Compiled {len(data)} entries in five languages.")
