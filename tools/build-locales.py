"""Compile the checked-in translation tables. OpenCC is a build-only dependency."""
import json
from pathlib import Path
from opencc import OpenCC

root = Path(__file__).resolve().parents[1]
traditional = OpenCC("s2twp")
data = {}
for source in sorted((root / "tools/locales").glob("*.tsv")):
    for number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
        if not line:
            continue
        fields = [value.replace(r"\n", "\n") for value in line.split("\t")]
        if len(fields) != 11:
            raise ValueError(f"{source.name}:{number}: expected 11 columns, got {len(fields)}")
        zh, en, ja, ko, th, *expanded = fields
        if zh in data:
            raise ValueError(f"Duplicate translation: {zh}")
        if any(not text for text in expanded) and zh != ' 回合':
            raise ValueError(f"{source.name}:{number}: missing expanded translation")
        data[zh] = [en, ja, ko, traditional.convert(zh), th, *expanded]
overrides = {}
for source in sorted((root / 'tools/locales').glob('overrides-*.json')):
    for locale, entries in json.loads(source.read_text(encoding='utf-8')).items():
        overrides.setdefault(locale, {}).update(entries)
for locale in ['hi', 'ar', 'ru', 'ur', 'bn', 'tr', 'fil', 'mr', 'te', 'ta']:
    source = root / 'tools/locales/expanded' / (locale + '.json')
    entries = json.loads(source.read_text(encoding='utf-8'))
    if set(entries) != set(data):
        raise ValueError(f'{locale}: translation keys must match the source catalog')
    if set(overrides.get(locale, {})) - set(data):
        raise ValueError(f'{locale}: override keys must match the source catalog')
    entries.update(overrides.get(locale, {}))
    for key, values in data.items():
        if not isinstance(entries[key], str) or (not entries[key] and key != ' 回合'):
            raise ValueError(f'{locale}: empty translation for {key}')
        value = entries[key]
        if '\n' in values[0] and '\n' not in value:
            value = value.replace(' / ', '\n')
            if values[0].startswith('\n'):
                value = '\n' + value.lstrip(' /\n')
        values.append(value)
out = "// Generated by tools/build-locales.py; edit tools/locales/*.tsv and expanded/*.json.\n"
out += "export const TRANSLATIONS:Record<string,string[]>=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "assets/scripts/PMTranslations.ts").write_text(out, encoding="utf-8")
print(f"Compiled {len(data)} entries in twenty-one translated languages.")
