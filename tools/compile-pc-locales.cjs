const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const ROOT=path.resolve(__dirname,'..');
const LOCALES=['en','ja','ko','zh-TW','th','pt-BR','es-419','id','vi','de','fr','hi','ar','ru','ur','bn','tr','fil','mr','te','ta'];
function compile(){
  const catalog=JSON.parse(fs.readFileSync(path.join(ROOT,'pc/i18n/source.json'),'utf8'));
  const rows=Array.isArray(catalog)?catalog:catalog.entries;
  assert(rows?.length,'PC source catalog is empty');
  const ids=new Set(rows.map(row=>row.id));assert.equal(ids.size,rows.length,'duplicate PC source ID');
  const table=Object.fromEntries(rows.map(row=>[row.source,{}]));assert.equal(Object.keys(table).length,rows.length,'duplicate PC source text');
  for(const locale of LOCALES){
    const entries=JSON.parse(fs.readFileSync(path.join(ROOT,'pc/i18n/locales',locale+'.json'),'utf8'));
    assert.deepEqual(Object.keys(entries).sort(),[...ids].sort(),locale+' catalog IDs differ');
    for(const row of rows){
      const value=entries[row.id];assert.equal(typeof value,'string',locale+' '+row.id);assert(value.trim(),locale+' '+row.id+' is empty');
      const tokens=s=>(s.match(/\{[a-zA-Z][\w]*\}/g)||[]).sort();
      assert.deepEqual(tokens(value),tokens(row.source),locale+' '+row.id+' placeholders');
      assert.equal((value.match(/\n/g)||[]).length,(row.source.match(/\n/g)||[]).length,locale+' '+row.id+' line breaks');
      for(const symbol of ['×','%','→','＞'])if(row.source.includes(symbol))assert(value.includes(symbol),locale+' '+row.id+' missing '+symbol);
      assert(!/[\u0000-\u0008\u000b\u000c\u000e-\u001f\ufffd]/.test(value),locale+' '+row.id+' invalid characters');
      table[row.source][locale]=value;
    }
  }
  const file=path.join(ROOT,'pc/game/PCTranslations.ts');
  const source='// Generated by tools/compile-pc-locales.cjs from the PC-only locale catalogs.\n// Edit pc/i18n/locales/*.json, then rebuild. Mobile translations are unchanged.\nexport const PC_TRANSLATIONS:Record<string,Record<string,string>>='+JSON.stringify(table,null,2)+';\n';
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==source)fs.writeFileSync(file,source);
  return {locales:LOCALES.length,keys:rows.length,translations:LOCALES.length*rows.length};
}
if(require.main===module)console.log(JSON.stringify(compile()));module.exports={compile,LOCALES};
